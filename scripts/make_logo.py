#!/usr/bin/env python3
"""Build logo and favicon SVGs with all text converted to paths (fontTools).

Writes public/logo.svg, public/favicon.svg and src/components/Logo.astro.
PNG icons are rendered afterwards by scripts/make_icons.mjs.
"""
import os
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, "node_modules/@fontsource/open-sans/files")
INK, GREEN, LIME = "#111111", "#6cc82a", "#a6ef39"


def text_path(text, weight, size, x0, baseline, tracking=0.0):
    font = TTFont(os.path.join(FONTS, "open-sans-latin-%d-normal.woff2" % weight))
    gs = font.getGlyphSet()
    cmap = font.getBestCmap()
    upm = font["head"].unitsPerEm
    scale = size / upm
    pen = SVGPathPen(gs)
    x = x0
    for ch in text:
        name = cmap[ord(ch)]
        tp = TransformPen(pen, (scale, 0, 0, -scale, x, baseline))
        gs[name].draw(tp)
        x += gs[name].width * scale + tracking
    return pen.getCommands(), x


def mark(x, y, s):
    font = TTFont(os.path.join(FONTS, "open-sans-latin-800-normal.woff2"))
    w = font.getGlyphSet()[font.getBestCmap()[ord("B")]].width * (s * 0.78) / font["head"].unitsPerEm
    bx = x + (s - w) / 2
    by = y + s * 0.78
    b, _ = text_path("B", 800, s * 0.78, bx, by)
    r = s * 0.22
    return (
        '<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" rx="%.1f" fill="%s"/>' % (x, y, s, s, r, GREEN)
        + '<circle cx="%.1f" cy="%.1f" r="%.1f" fill="%s"/>' % (x + s * 0.84, y + s * 0.84, s * 0.09, LIME)
        + '<path d="%s" fill="#fff"/>' % b
    )


def main():
    h = 44
    word, x1 = text_path("Brandella", 800, 27, 54, 31, -0.4)
    sub, x2 = text_path("Journal", 600, 27, x1 + 7, 31, -0.2)
    width = round(x2 + 2)
    body = mark(0, 2, 40) + '<path d="%s" fill="currentColor"/>' % word + '<path d="%s" fill="%s"/>' % (sub, GREEN)
    svg_inline = ('<svg class="logo" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" width="%d" height="%d" role="img" aria-label="Brandella Journal">%s</svg>'
                  % (width, h, width, h, body))
    with open(os.path.join(ROOT, "public/logo.svg"), "w") as fh:
        fh.write(svg_inline.replace(' class="logo"', "").replace("currentColor", INK))
    with open(os.path.join(ROOT, "src/components/Logo.astro"), "w") as fh:
        fh.write("---\n// Generated by scripts/make_logo.py, do not edit by hand.\n---\n" + svg_inline + "\n")
    fav = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">%s</svg>' % mark(0, 0, 64)
    with open(os.path.join(ROOT, "public/favicon.svg"), "w") as fh:
        fh.write(fav)
    print("logo width", width)


if __name__ == "__main__":
    main()
